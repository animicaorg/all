from __future__ import annotations

import json
import logging
import os
from dataclasses import dataclass
from pathlib import Path
from typing import Callable, Optional


VerifyFn = Callable[[bytes, bytes, bytes], bool]
SignFn = Callable[[bytes, bytes], bytes]

log = logging.getLogger(__name__)

_ALLOWED_OVERRIDE_WARNED = False
_PQ_ALLOWLIST_WARNED = False

_SCHEME_NAME_TO_ID = {
    "dilithium3": 1,
    "pq-1952-byte": 1,
    "sphincs_shake_128s": 2,
    "sphincs128s": 2,
    "sphincs+128s": 2,
    # v2 — real FIPS 204 ML-DSA-65
    "ml_dsa_65": 11,
    "ml-dsa-65": 11,
    "ml-dsa": 11,
}

# ANM-C01: mainnet MUST require the real FIPS-204 scheme (ml_dsa_65 / id 11) and
# MUST NOT require the forgeable commitment-style stubs (ids 1 & 2). This was
# {1: (1, 2)}, which forced the forgeable schemes to stay enabled at startup via
# assert_required_pq_for_chain. Schemes 1-4 are now disabled by default (see
# CANONICAL_SCHEME_SPECS) so verify_signature rejects them; only 11 is accepted.
# Forward-only: historical blocks are grandfathered by the pq_hardening height
# gate (core.network_params), so existing history is never re-validated.
_CHAIN_REQUIRED_SCHEMES: dict[int, tuple[int, ...]] = {1: (11,)}


def required_schemes_for_chain(chain_id: int) -> tuple[int, ...]:
    return _CHAIN_REQUIRED_SCHEMES.get(chain_id, tuple())


@dataclass(frozen=True)
class SchemeSpec:
    scheme_id: int
    name: str
    pubkey_lengths: tuple[int, ...]
    signature_lengths: tuple[int, ...]
    enabled_by_default: bool = True


@dataclass
class RuntimeScheme:
    spec: SchemeSpec
    sign_fn: Optional[SignFn] = None
    verify_fn: Optional[VerifyFn] = None
    enabled: bool = False
    reason_if_disabled: Optional[str] = None


@dataclass(frozen=True)
class PolicyOverride:
    enabled: bool
    mode: str
    allow_sig_schemes: tuple[int, ...]
    deny_sig_schemes: tuple[int, ...]
    comment: str
    file_path: str | None


@dataclass(frozen=True)
class PolicyEvaluation:
    scheme_id: int
    name: str
    enabled_by_code: bool
    enabled_by_policy: bool
    enabled_effective: bool
    reason_if_disabled: str | None
    policy_root: str


